const { PrismaClient } = require('@prisma/client');
const prisma = new PrismaClient();

async function main() {
  const category = await prisma.category.findFirst({
    where: { name: 'إجراءات الدخول المدرسي' }
  });

  if (!category) {
    console.error('Category not found');
    return;
  }

  const content = `إليك دليل مفصل وشامل لعملية تدبير الفائض والخصاص، مصمم خصيصاً لمساعدتك كأستاذ(ة) على فهم حقوقك، واجباتك، وكيفية حماية استقرارك المهني أثناء هذه العملية.

## 1. كيف تُحسب نقاطك بدقة؟ (شرح شبكة التنقيط)
إذا أعلنت المديرية عن وجود فائض في مادتك أو سلكك داخل المؤسسة، يتم ترتيب جميع أساتذة تلك المادة بناءً على المجموع الإجمالي للنقاط التالية:

* الأقدمية العامة: 1 نقطة عن كل سنة عمل (تُحتسب من تاريخ أول توظيف في الوظيفة العمومية).
* الأقدمية بالنيابة/المديرية: 1 نقطة عن كل سنة عمل داخل المديرية الإقليمية الحالية.
* الأقدمية بالمؤسسة: 2 نقطتان عن كل سنة عمل داخل مؤسستك الحالية.

## ⚠️ حالات خاصة لفك التساوي:
إذا تساوى أستاذان أو أكثر في المجموع النهائي للنقاط، يتم اللجوء إلى المعايير التالية بالتتابع للفصل بينهم:
   1. الأقدمية العامة (صاحب الأقدمية الأكبر ينجو من الفائض).
   2. الأقدمية بالمديرية.
   3. الأقدمية بالمؤسسة.
   4. عامل السن: يُستثنى الأكبر سناً، ويُعتبر الأصغر سناً هو الفائض.

## 🚫 فئات مُستثناة من الفائض:
يُستثنى من التسمية كفائض (بشروط وموافقة الإدارة) الأساتذة المبرزون، حاملو شهادة الدكتوراه، أو من يعانون من ظروف صحية حرجة ومثبتة بملف طبي مصادق عليه من اللجان الطبية المختصة.

## 2. مراحل العملية: خطوة بخطوة من التسمية إلى التكليف
### المرحلة الأولى: صدور اللوائح
تنشر المديرية الإقليمية عبر موقعها أو المؤسسات وثيقتين رسميتين:
   1. لائحة الأساتذة الفائضين: تضم أسماء الأساتذة المرتبين في أسفل اللائحة بكل مؤسسة.
   2. لائحة الخصاص (المناصب الشاغرة): تضم المؤسسات التي تعاني من نقص في هيئة التدريس ومقدار الخصاص بها.

### المرحلة الثانية: تعبئة بطاقة الرغبات
إذا ورد اسمك في لائحة الفائض، يتعين عليك تعبئة بطاقة الرغبات (طلب التكليف لسد الخصاص):
* يمكنك اختيار عدد معين من المؤسسات الشاغرة وترتيبها حسب أفضليتها بالنسبة لك.
* يتم توقيع الطلب من طرفك، ثم يوقعه مدير مؤسستك الأصلية ويوجهه إلى المديرية الإقليمية عبر السلم الإداري.

### المرحلة الثالثة: معالجة الطلبات وإصدار التكليفات
تدرس لجنة إقليمية مشتركة (تضم المديرية والفرقاء الاجتماعيين/النقابات) الطلبات بناءً على الأولويات الجغرافية:
   1. الأولوية 1 (داخل نفس الجماعة): يتم تلبية رغبات الأساتذة الفائضين في مؤسسات تابعة لنفس الجماعة (الحضرية أو القروية) التي يشتغلون بها أولاً.
   2. الأولوية 2 (الجماعات المجاورة): في حال عدم وجود مناصب شاغرة في جماعتك الأصلية، تُدرس رغباتك في الجماعات الأقرب فالأقرب جغرافياً.
   3. التكليف التلقائي (الإنزال): إذا لم تعبئ بطاقة الرغبات، أو لم تكفِ اختياراتك لتغطية منصب، يحق للمديرية تكليفك تلقائياً في أي منصب شاغر بالإقليم لضمان الزمن المدرسي للتلاميذ.

## 3. الوضعية القانونية للأستاذ المُكلّف (حقوق وضمانات)
بصفتك أستاذاً فائضاً تم تكليفه بمؤسسة أخرى، يضمن لك القانون الحقوق التالية:
* التكليف مؤقت: هذا التكليف ينتهي بقوة القانون بنهاية الموسم الدراسي الحالي (30 يونيو/يوليو).
* الاحتفاظ بالمنصب الأصلي: تظل تابعاً إدارياً لمؤسستك الأصلية التي اعتبرت فيها فائضاً، ولا تفقد منصبك الاستقراري فيها.
* الحركة الانتقالية: تحتفظ بكامل حقك في المشاركة في الحركة الانتقالية الوطنية أو الجهوية بناءً على وضعيتك في مؤسستك الأصلية (وتستمر أقدميتك بالمؤسسة في الاحتساب بشكل طبيعي).
* الجدول الزمني: يجب ألّا يتجاوز حصيصك الساعي الأسبوعي القانوني المعمول به في سلكك التعليمي (إلا في حالات الساعات الإضافية الطوعية).

لمساعدتك في مراجعة وضعيتك بدقة، يرجى تحديد:
* هل تريد طريقة احتساب نقاطك (أعلمني بأقدميتك العامة، وبالمؤسسة، وبالمديرية لأحسبها لك)؟
* هل تحتاج إلى نموذج جاهز لبطاقة الرغبات لكي تطلع على صيغتها؟`;

  await prisma.knowledgeEntry.create({
    data: {
      question: 'كيف تتم عملية تدبير الفائض والخصاص؟',
      answer: content,
      categoryId: category.id
    }
  });

  console.log('Knowledge entry added successfully.');
}

main()
  .catch(e => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
