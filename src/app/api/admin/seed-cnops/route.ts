import { NextResponse } from "next/server";
import { prisma } from "@/lib/prisma";

export async function GET() {
  try {
    let cat = await prisma.category.findFirst({
      where: { name: { contains: "الوظيفة العمومية" } }
    });

    if (!cat) {
      cat = await prisma.category.create({
        data: {
          name: "التغطية الصحية والتعاضدية CNOPS",
          description: "ملفات المرض والتعويضات والتغطية الصحية لموظفي التعليم",
          color: "#059669",
          icon: "ShieldPlus"
        }
      });
    }

    const title = "الأجل القانوني لإيداع ملف استرجاع مصاريف العلاج لدى كنوبس CNOPS والتعاضدية العامة MGEN (مدة صلاحية الملف الطبي 60 يوماً)";
    const content = `الأجل القانوني لإيداع ملف استرجاع مصاريف العلاج لدى الصندوق الوطني لمنظمات الاحتياط الاجتماعي (CNOPS) والتعاضدية العامة للتربية الوطنية (MGEN) هو **60 يوماً**.

---

### تفاصيل الآجال القانونية حسب نوع الملف الطبي:

1. **العلاجات العادية (استشارة طبية، أدوية، تحاليل مخبرية، فحوصات بالأشعة، ترويض طبي):**
- يُحتسب أجل **60 يوماً** ابتداءً من **تاريخ أول عمل طبي** (تاريخ أول زيارة للطبيب المدونة في ورقة العلاج، وليس تاريخ شراء الأدوية أو تاريخ التحاليل اللاحقة).

2. **ملفات الاستشفاء والعمليات الجراحية (استرجاع المصاريف بعد الأداء):**
- يُحتسب أجل **60 يوماً** ابتداءً من **تاريخ الخروج** الرسمي من المصحة أو المستشفى المدون في فاتورة وبيان الاستشفاء.

3. **وثيقة التحمل المسبق (Prise en charge - PEC):**
- مدة صلاحية موافقة كنوبس على التحمل المباشر للمصاريف هي **30 يوماً** ابتداءً من تاريخ إصدارها (قابلة للتجديد بطلب جديد إذا تأجل التدخل الطبي).

4. **ملفات الأمراض المزمنة أو المكلفة وطويلة الأمد (ALD / ALC):**
- صلاحية قرار الإعفاء والتكفل بالأمراض المزمنة تمتد عادة إلى **5 سنوات** (أو مدى الحياة لبعض الحالات المستقرة) بعد مصادقة المراقبة الطبية لكنوبس.

---

### أسباب شائعة تؤدي لسقوط الملف بالتقادم أو الرفض:

- **تجاوز الـ 60 يوماً (Hors délai):** يُرفض الملف تلقائياً بدعوى «خارج الأجل القانوني» إذا فاق الفارق بين تاريخ أول تأشيرة طبية وتاريخ إيداع الملف بالتعاضدية 60 يوماً.
- **نقص التواريخ أو الأختام:** إغفال تاريخ الفحص من طرف الطبيب المعالج، أو خاتم وتاريخ الصيدلي/المختبر، يجعل الملف عرضة للإرجاع حتى لو أودع داخل الأجل.
- **علب الأدوية والأرقام التسلسلية:** ضرورة إلصاق الأرقام التسلسلية ورمز الاستجابة السريعة (رمز الباركود / Vignettes) وثمن البيع للعموم (PPM) الخاص بكل دواء تم اقتناؤه، مع إرفاق الوصفة الطبية الأصلية (Ordonnance).
- **توقيع ورقة العلاج:** وجوب توقيع المنخرط والتأكد من وضوح رقم التأجير (PPR) ورقم التسجيل بالتعاضدية.`;

    const entry = await prisma.knowledgeEntry.upsert({
      where: { id: "cnops-delai-remboursement-60-jours" },
      create: {
        id: "cnops-delai-remboursement-60-jours",
        categoryId: cat.id,
        title,
        content,
        priority: 100,
        isActive: true,
        metadata: { tags: ["cnops", "كنوبس", "ملف طبي", "استرجاع مصاريف", "60 يوما", "MGEN"] }
      },
      update: {
        title,
        content,
        priority: 100,
        isActive: true,
        updatedAt: new Date()
      }
    });

    return NextResponse.json({ success: true, entry });
  } catch (error: any) {
    return NextResponse.json({ error: error?.message || String(error) }, { status: 500 });
  }
}
